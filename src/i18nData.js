/**
 * Returns translated string for a given key and language.
 * Clean, fast lookup with fallback to English then key as-is.
 */
export function getTrans(key, lang = 'en') {
    if (!key) return '';

    // Direct match
    if (DATA_TRANSLATIONS[lang] && DATA_TRANSLATIONS[lang][key] !== undefined) {
        return DATA_TRANSLATIONS[lang][key];
    }

    // Fallback to English
    if (lang !== 'en' && DATA_TRANSLATIONS['en'] && DATA_TRANSLATIONS['en'][key] !== undefined) {
        return DATA_TRANSLATIONS['en'][key];
    }

    // Return key as-is
    return key;
}